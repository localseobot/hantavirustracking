/** Sum a numeric field across all country rows. */
export function totals() {
  let cases = 0;
  let deaths = 0;
  let countriesWithCases = 0;
  for (const c of COUNTRIES) {
    cases += c.cases;
    deaths += c.deaths;
    if (c.cases > 0) countriesWithCases += 1;
  }
  const cfr = cases > 0 ? (deaths / cases) * 100 : 0;
  return { cases, deaths, countriesWithCases, cfr };
}
